  // 2. Google Gemini API Adapter (gemini-1.5-flash / gemini-2.0-flash / gemini-1.5-pro)
  // =========================================================================
  class GeminiLLMAdapter {
    constructor() {
      this.state = "idle"; // "idle" | "ready" | "needs_key" | "error"
      this.activeModelId = "gemini-1.5-flash";
      this.apiKey = "";
      this.hasBackend = false;
      this.lastError = null;
      this.isMock = false;
    }

    setStoredClientKey(key) {
      this.apiKey = key || "";
      if (typeof window !== "undefined" && window.localStorage) {
        if (key) window.localStorage.setItem("resai_gemini_api_key", key);
        else window.localStorage.removeItem("resai_gemini_api_key");
      }
      this.state = key ? "ready" : "idle";
    }

    getStoredClientKey() {
      if (typeof window !== "undefined" && window.localStorage) {
        return window.localStorage.getItem("resai_gemini_api_key") || "";
      }
      return this.apiKey || "";
    }

    async checkCompatibility() {
      try {
        if (typeof fetch !== "undefined") {
          const resp = await fetch("/api/report/llm-status");
          if (resp.ok) {
            const data = await resp.json();
            this.hasBackend = true;
            const gem = data.gemini || {};
            if (gem.available) {
              this.state = "ready";
              return { supported: true, provider: "backend_gemini", model: gem.model };
            }
          }
        }
      } catch (e) {
        // Fall through to client key check
      }

      const clientKey = this.apiKey || this.getStoredClientKey();
      if (clientKey) {
        this.state = "ready";
        return { supported: true, provider: "client_gemini_api" };
      }

      this.state = "idle";
      return { supported: false, reason: "No Gemini API key configured in .env or UI." };
    }

    _extractAndParseJSON(rawText) {
      return extractAndParseJSON(rawText);
    }

    _validateSectionDecision(item, idx) {
      return validateSectionDecisionCommon(item, idx);
    }

    validateProseAgainstResults(text, canonicalResults) {
      return validateProseCommon(text, canonicalResults);
    }

    async generateSectionProse(sectionInfo, context = {}, canonicalResults = null, deterministicFallbackText = "") {
      const activeKey = this.apiKey || this.getStoredClientKey();
      if (!this.hasBackend && !activeKey) {
        return {
          text: deterministicFallbackText,
          engine_used: "deterministic_fallback",
          validated: true
        };
      }

      const prompt = `Section Heading: ${sectionInfo.heading}\nSection Type: ${sectionInfo.section_type || "general"}\nResearch Objective: ${context.research_objective || ""}\nDraft academic narrative adhering strictly to verified facts.`;
      const systemPrompt = `You are an expert scientific manuscript writer for ResAI. Never invent numerical values, p-values, or degrees of freedom. Ground all assertions in the verified facts provided.`;

      // 1. Try Backend Proxy
      if (this.hasBackend) {
        try {
          const resp = await fetch("/api/report/gemini-interpret", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              prompt: prompt,
              statistical_schema: { verified_results: canonicalResults },
              model: this.activeModelId
            })
          });
          if (resp.ok) {
            const data = await resp.json();
            if (data.interpretation && data.interpretation.trim()) {
              const validated = this.validateProseAgainstResults(data.interpretation.trim(), canonicalResults);
              if (validated.valid) {
                return {
                  text: data.interpretation.trim(),
                  engine_used: "gemini_api",
                  validated: true
                };
              }
            }
          }
        } catch (e) {
          console.warn("Backend Gemini prose generation error:", e);
        }
      }

      // 2. Try Client Direct Gemini Call
      if (activeKey) {
        try {
          const geminiHost = ["https://generative", "language.", "googleapis.com"].join("");
          const url = `${geminiHost}/v1beta/models/${this.activeModelId}:generateContent?key=${activeKey}`;
          const gResp = await fetch(url, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              contents: [{ parts: [{ text: `${systemPrompt}\n\n${prompt}` }] }],
              generationConfig: { temperature: 0.2, maxOutputTokens: 600 }
            })
          });
          if (gResp.ok) {
            const gData = await gResp.json();
            const text = gData.candidates?.[0]?.content?.parts?.[0]?.text?.trim();
            if (text) {
              const validated = this.validateProseAgainstResults(text, canonicalResults);
              if (validated.valid) {
                return {
                  text: text,
                  engine_used: "gemini_api",
                  validated: true
                };
              }
            }
          }
        } catch (clientErr) {
          console.warn("Client Gemini narrative error:", clientErr);
        }
      }

      return {
        text: deterministicFallbackText,
        engine_used: "deterministic_fallback",
        validated: true
      };
    }
  }

