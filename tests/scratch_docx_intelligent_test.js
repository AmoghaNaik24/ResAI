const fs = require('fs');

function isInstructionOrExampleParagraph(text) {
  if (!text || typeof text !== "string") return false;
  const trimmed = text.trim();
  if (!trimmed) return false;

  if (/_{3,}/.test(trimmed)) return true;
  if (/\[(insert|your|university|course|date|instructor|author|title|name)[^\]]*\]/i.test(trimmed)) return true;
  if (/gentext\s*(group|\.ai)|generated\s+by\s+gentext|template\s+by\s+microsoft/i.test(trimmed)) return true;

  const instructionPatterns = [
    /^(write|provide|compose|summarize|begin|state|describe|explain|detail|discuss|present|replace|use|ensure|double-space|margins|do not use|include at least)\b/i,
    /\b(write a concise abstract|approximately 150 to 250 words|between 150 and 250 words)\b/i,
    /\b(replace every blank line|replace with your own|insert your text here|paste your text here)\b/i,
    /\b(use a professional academic layout|double-spaced with 1-inch margins|times new roman 12pt|apa 7th edition formatting)\b/i,
    /\b(this section should describe|this section should summarize|in this section, provide)\b/i,
    /\b(briefly summarize the most relevant scholarly sources|cite at least 3-5 peer-reviewed)\b/i,
    /\b(begin the introduction by establishing the research problem)\b/i,
    /\b(example abstract sentence|example paragraph|for example, if you studied)\b/i
  ];

  return instructionPatterns.some(pat => pat.test(trimmed));
}

function replaceWordXmlIntelligent(xmlString, resMap, sectionReplacementMap = {}) {
  let currentSectionHeading = "General";

  return xmlString.replace(/<w:p\b[\s\S]*?<\/w:p>/g, (paraXml) => {
    const tRegex = /(<w:t\b[^>]*>)([\s\S]*?)(<\/w:t>)/g;
    const matches = [];
    let m;
    while ((m = tRegex.exec(paraXml)) !== null) {
      matches.push({ full: m[0], open: m[1], text: m[2], close: m[3] });
    }
    if (matches.length === 0) return paraXml;

    const combinedText = matches.map(m => m.text).join("");
    const trimmed = combinedText.trim();
    if (!trimmed) return paraXml;

    // Detect section heading
    const isHeading = /<w:pStyle[^>]*w:val="([^"]*Heading[^"]*|[^"]*Title[^"]*)"/i.test(paraXml) ||
                      /^(Abstract|1\.\s+Introduction|2\.\s+Methodology|3\.\s+Results|4\.\s+Discussion|5\.\s+Limitations|6\.\s+Conclusion|References|Formatting Guidelines)/i.test(trimmed);
    if (isHeading) {
      currentSectionHeading = trimmed.toLowerCase();
      // If heading is "Formatting Guidelines", we can clear it or leave clean
      if (/guideline|formatting advice|template notes/i.test(trimmed)) {
        return ""; // Omit entire formatting section
      }
      return paraXml; // Keep valid section headings
    }

    // Check if paragraph is branding
    if (/gentext\s*(group|\.ai)|generated\s+by\s+gentext|template\s+by\s+microsoft/i.test(trimmed)) {
      return ""; // Omit branding
    }

    // Check if paragraph is in an omitted section
    if (/guideline|formatting advice|template notes/i.test(currentSectionHeading)) {
      return ""; // Omit paragraph
    }

    // Check if paragraph is an instruction or placeholder blank
    let updatedText = combinedText;
    if (isInstructionOrExampleParagraph(trimmed)) {
      // Find matching replacement text for current section if available
      for (const [secKey, replacement] of Object.entries(sectionReplacementMap)) {
        if (currentSectionHeading.includes(secKey.toLowerCase())) {
          updatedText = replacement;
          break;
        }
      }
      // If no section replacement provided, and it is pure instruction, omit
      if (updatedText === combinedText) {
        return "";
      }
    }

    // Replace placeholders
    Object.keys(resMap).forEach(key => {
      const ph = `{{${key}}}`;
      if (updatedText.includes(ph)) {
        updatedText = updatedText.split(ph).join(resMap[key].formatted_value || String(resMap[key].value || ""));
      }
      const phBrackets = `[${key}]`;
      if (updatedText.includes(phBrackets)) {
        updatedText = updatedText.split(phBrackets).join(resMap[key].formatted_value || String(resMap[key].value || ""));
      }
    });

    if (updatedText === combinedText) return paraXml;

    let matchIdx = 0;
    return paraXml.replace(tRegex, (tTag, open, text, close) => {
      if (matchIdx === 0) {
        matchIdx++;
        const hasSpaceAttr = open.includes("xml:space");
        const safeOpen = hasSpaceAttr ? open : open.replace("<w:t", '<w:t xml:space="preserve"');
        return `${safeOpen}${updatedText}${close}`;
      } else {
        matchIdx++;
        return `${open}${close}`;
      }
    });
  });
}

// Test with an academic template XML containing instructions, blanks, branding, and placeholders
const inputXml = '<w:document>' +
  '<w:p><w:r><w:t>Generated by GenText Group — gentext.ai</w:t></w:r></w:p>' +
  '<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Abstract</w:t></w:r></w:p>' +
  '<w:p><w:r><w:t>Write a concise abstract of approximately 150 to 250 words.</w:t></w:r></w:p>' +
  '<w:p><w:r><w:t>The purpose of this study was to examine ________ in a sample of ________.</w:t></w:r></w:p>' +
  '<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Results</w:t></w:r></w:p>' +
  '<w:p><w:r><w:t>Descriptive summaries revealed a mean of {{mean_score}} (SD = {{standard_deviation}}).</w:t></w:r></w:p>' +
  '<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Formatting Guidelines</w:t></w:r></w:p>' +
  '<w:p><w:r><w:t>Use double-spaced lines with 1-inch margins and Times New Roman font.</w:t></w:r></w:p>' +
  '</w:document>';

const resMap = {
  mean_score: { formatted_value: "19.11" },
  standard_deviation: { formatted_value: "6.96" }
};

const sectionReplacements = {
  abstract: "This empirical study evaluated quantitative distributions across N = 8 validated experimental observations."
};

const outputXml = replaceWordXmlIntelligent(inputXml, resMap, sectionReplacements);

console.log("=== OUTPUT XML ===");
console.log(outputXml);
console.assert(!outputXml.includes("gentext.ai"), "Must omit gentext branding");
console.assert(!outputXml.includes("Write a concise abstract"), "Must omit abstract instructions");
console.assert(!outputXml.includes("________"), "Must omit blank underscores");
console.assert(!outputXml.includes("Formatting Guidelines"), "Must omit formatting guidelines");
console.assert(outputXml.includes("This empirical study evaluated"), "Must contain adapted abstract");
console.assert(outputXml.includes("mean of 19.11 (SD = 6.96)"), "Must contain verified results");
